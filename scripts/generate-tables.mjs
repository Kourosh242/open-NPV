import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const provenance = JSON.parse(await readFile('vendor/pantegnos/provenance.json', 'utf8'));
const names = ['tyboxes.bin', 'mbl.bin', 'xor.bin', 'tboxes_last.bin', 'tboxes_last_v2.bin', 'npvt_last.bin', 'gen2_tables.bin.z'];
const entries = [];
for (const name of names) {
  const bytes = await readFile(`vendor/pantegnos/assets/${name}`);
  const hash = createHash('sha256').update(bytes).digest('hex');
  if (hash !== provenance.files[name].sha256) throw new Error(`Table checksum mismatch: ${name}`);
  entries.push(`export const ${name.replace(/[^a-z0-9]/gi, '_')} = '${bytes.toString('base64')}';`);
}
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/tables.ts', `// Generated by scripts/generate-tables.mjs. Do not edit.\n// Source: Pantegnos ${provenance.commit}, AGPL-3.0-only.\n${entries.join('\n')}\n`);
console.log('Format tables verified against pinned SHA-256 checksums.');
